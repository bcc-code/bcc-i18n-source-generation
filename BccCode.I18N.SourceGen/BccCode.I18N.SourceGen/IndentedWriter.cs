using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace BccCode.I18N.SourceGen;

/// <summary>Writes C# source into a single <see cref="StringBuilder"/> with four-space indentation.</summary>
internal sealed class IndentedWriter
{
    private const string IndentUnit = "    ";

    private readonly StringBuilder _builder = new(4096);
    private int _indentLevel;
    private bool _atLineStart = true;

    public IndentedWriter Indent()
    {
        _indentLevel++;
        return this;
    }

    public IndentedWriter Outdent()
    {
        _indentLevel--;
        return this;
    }

    public IndentedWriter Append(string text)
    {
        WriteIndentIfNeeded();
        _builder.Append(text);
        return this;
    }

    public IndentedWriter Append(char character)
    {
        WriteIndentIfNeeded();
        _builder.Append(character);
        return this;
    }

    public IndentedWriter AppendLine(string text)
    {
        Append(text);
        return AppendLine();
    }

    /// <summary>Ends the current line. Blank lines are written without indentation.</summary>
    public IndentedWriter AppendLine()
    {
        _builder.AppendLine();
        _atLineStart = true;
        return this;
    }

    public IndentedWriter OpenBlock()
    {
        AppendLine("{");
        return Indent();
    }

    public IndentedWriter CloseBlock(string suffix = "")
    {
        Outdent();
        return AppendLine("}" + suffix);
    }

    public override string ToString() => _builder.ToString();

    private void WriteIndentIfNeeded()
    {
        if (!_atLineStart)
        {
            return;
        }

        for (var level = 0; level < _indentLevel; level++)
        {
            _builder.Append(IndentUnit);
        }

        _atLineStart = false;
    }
}

internal static class GeneratedFile
{
    private const string GeneratorName = "BccCode.I18N.SourceGen";

    private static readonly string GeneratorVersion =
        typeof(GeneratedFile).Assembly.GetName().Version?.ToString() ?? "1.0.0.0";

    /// <summary>
    /// Writes the file header and opens the namespace block (when a namespace is configured), then the class declaration.
    /// </summary>
    public static IndentedWriter Begin(string generatedNamespace, string className)
    {
        var writer = new IndentedWriter();
        writer.AppendLine("// <auto-generated/>");
        writer.AppendLine("#nullable enable");
        writer.AppendLine("#pragma warning disable CS8981 // The type name only contains lower-cased ascii characters. Such names may become reserved for the language.");
        writer.AppendLine();

        if (!string.IsNullOrWhiteSpace(generatedNamespace))
        {
            writer.Append("namespace ").AppendLine(generatedNamespace);
            writer.OpenBlock();
        }

        writer.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"").Append(GeneratorName).Append("\", \"")
            .Append(GeneratorVersion).AppendLine("\")]");
        writer.Append("public static class ").AppendLine(className);
        writer.OpenBlock();
        return writer;
    }

    public static void AddSource(SourceProductionContext context, IndentedWriter writer, string generatedNamespace, string className)
    {
        writer.CloseBlock();
        if (!string.IsNullOrWhiteSpace(generatedNamespace))
        {
            writer.CloseBlock();
        }

        context.AddSource(className + ".g.cs", SourceText.From(writer.ToString(), Encoding.UTF8));
    }
}
